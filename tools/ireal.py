"""Shared iReal Pro generator.

Each tune has tunes/<name>/ireal.py with its chord data and the list of
iReal exercises it wants; it calls build(). Output:
  ireal/<Title> - <exercise label>.html   one chart per exercise (irealbook://)
  ireal/<Title> - Exercises.html          playlist of those charts (irealb://)
  tunes/<name>/ireal-files.tex            LaTeX box listing the files
Chords are (degree, quality[, bass degree]) relative to the major key,
e.g. ("2", "-7"), ("b3", "7"), ("1", "^7", "5").
"""
import os, urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LETTERS = "CDEFGAB"; NAT = {"C":0,"D":2,"E":4,"F":5,"G":7,"A":9,"B":11}
MAJOR = [0,2,4,5,7,9,11]
ENH = {"Cb":"B","Fb":"E","E#":"F","B#":"C",
       "Cbb":"Bb","Dbb":"C","Ebb":"D","Fbb":"Eb","Gbb":"F","Abb":"G","Bbb":"A",
       "C##":"D","D##":"E","E##":"F#","F##":"G","G##":"A","A##":"B","B##":"C#"}

def note(key, deg):
    alt = deg.count('#') - deg.count('b'); n = int(deg.strip('#b'))
    kl, kacc = key[0], key[1:]
    ksemi = NAT[kl] + kacc.count('#') - kacc.count('b')
    letter = LETTERS[(LETTERS.index(kl) + n - 1) % 7]
    d = ((ksemi + MAJOR[n-1] + alt) - NAT[letter]) % 12
    acc = {0:"",1:"#",2:"##",11:"b",10:"bb"}[d]
    return ENH.get(letter+acc, letter+acc)

def chord(key, c):
    s = note(key, c[0]) + c[1]
    return s + ("/" + note(key, c[2]) if len(c) > 2 else "")

def bar(key, chords):
    c = [chord(key, x) for x in chords]
    if len(c) == 1: return c[0] + "   "
    if len(c) == 2: return c[0] + " " + c[1] + " "
    if len(c) == 3: return c[0] + " " + c[1] + "," + c[2]   # 3 chords: beats 1, 3, 4
    return ",".join(c[:4])                                   # 4 chords: one per beat

def progression(key, bars, sections):
    """sections: list of (label, n_bars), e.g. [("A",16),("B",16)]"""
    b = [bar(key, x) for x in bars]; out = []; i = 0
    for lab, n in sections:
        out.append("[*" + lab + "|".join(b[i:i+n]) + "]"); i += n
    p = "".join(out)
    return "[T44" + p[1:-1] + " Z"

def _obfusc50(s):
    n = list(s)
    for i in range(5): n[49-i], n[i] = s[i], s[49-i]
    for i in range(10, 24): n[49-i], n[i] = s[i], s[49-i]
    return "".join(n)

def scramble(s):
    r = ""
    while len(s) > 51:
        r += _obfusc50(s[:50]); s = s[50:]
    return r + s

# Exercise kinds available to every tune: id -> (file label, description, which chords)
EXERCISES = {
  "all-keys":  ("all keys", "Tune in all keys. Start in C; in iReal Pro Practice: key up 5 half steps at every repeat, 12 repeats.", "main", "C"),
  "main":      ("main changes", "Main changes, default key; transpose in the app to the tune's keys.", "main", None),
  "secondary": ("secondary changes", "Secondary / alternative changes, default key; transpose in the app.", "alt", None),
}

def _page(title, desc, url, label):
    return f"""<!DOCTYPE html><html><head><meta charset="utf-8"><title>{title}</title></head>
<body><h2>{title}</h2><p>{desc}</p><p><a href="{url}">{label}</a></p></body></html>"""

def _tex(s):
    return s.replace("&", r"\&").replace("#", r"\#").replace("_", r"\_")

def build(tune_dir, title, composer, style, key, main, alt, sections, exercises):
    out = os.path.join(ROOT, "ireal"); os.makedirs(out, exist_ok=True)
    alt_bars = [alt.get(i+1, main[i]) for i in range(len(main))]
    charts, items = [], []
    for ex in exercises:
        label, desc, which, k = EXERCISES[ex]
        k = k or key
        prog = progression(k, main if which == "main" else alt_bars, sections)
        name = f"{title} ({label})"
        fname = f"{title} - {label}.html"
        url = "irealbook://" + urllib.parse.quote(
            "=".join([name, composer, style, k, "n", prog]), safe="=")
        open(os.path.join(out, fname), "w").write(_page(fname[:-5], desc, url, "Import into iReal Pro"))
        charts.append("=".join([name, composer, "", style, k, "", "1r34LbKcu7" + scramble(prog), "", "0", "0"]))
        items.append((fname, desc))
    pl = f"{title} - Exercises"
    url = "irealb://" + urllib.parse.quote("===".join(charts) + "===" + pl, safe="=")
    open(os.path.join(out, pl + ".html"), "w").write(
        _page(pl, f"{len(charts)} exercise charts as one iReal Pro playlist.", url, "Import playlist into iReal Pro"))
    items.append((pl + ".html", "Playlist with all the charts above."))
    with open(os.path.join(tune_dir, "ireal-files.tex"), "w") as f:
        f.write("% Generated by ireal.py -- do not edit\n\\begin{irealfiles}\n")
        for fn, d in items:
            f.write(f"\\irealfile{{{_tex(fn)}}}{{{_tex(d)}}}\n")
        f.write("\\end{irealfiles}\n")
    return items
