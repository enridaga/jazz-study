#!/usr/bin/env python3
"""Generate guitar tabs for the pattern book.

Reads every \\patterntab[key]{degrees} in patterns/*.tex and writes a TikZ tab
to patterns/tabs/<pattern>-<n>.tex, plus patterns/tabs/list.tex (all patterns,
used by patternbook.tex). Degrees: [#|b]N with ' (octave up) or , (octave down);
| is a bar line. Default reference key: G (1 = G on the 3rd string, open/fret 0).
Optional explicit string per note: 1,@6 = degree 1, octave down, on the 6th (low E) string;
give it for every note of a line or for none. '' and ,, are two octaves up/down.
Fingering (without @): the lowest position from the 2nd fret up (4-fret box, one-fret stretch) that plays
every note; within it, each note takes the string whose fret is nearest the box centre.
"""
import os, re, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAT = os.path.join(ROOT, "patterns"); OUT = os.path.join(PAT, "tabs")
OPEN = [64, 59, 55, 50, 45, 40]           # strings 1..6 (high E .. low E), MIDI
NAMES = ["e", "B", "G", "D", "A", "E"]
MAJOR = [0, 2, 4, 5, 7, 9, 11]
PC = {"C":0,"D":2,"E":4,"F":5,"G":7,"A":9,"B":11}
TOK = re.compile(r"([#b]*)(\d)('*|,*)(?:@([1-6]))?$")

def tonic(key):
    pc = (PC[key[0]] + key[1:].count('#') - key[1:].count('b')) % 12
    m = 48 + pc
    return m + 12 if m < 52 else m       # 1 between E3 and D#4

def parse(line, key):
    out = []
    for t in line.split():
        if t == "|": out.append("|"); continue
        a, n, o, st = TOK.match(t).groups()
        midi = tonic(key) + MAJOR[int(n)-1] + a.count('#') - a.count('b') \
               + 12 * (o.count("'") - o.count(","))
        d = n
        for _ in range(o.count("'")): d = r"\hi{" + d + "}"
        for _ in range(o.count(",")): d = r"\lo{" + d + "}"
        label = r"\mel{" + a.replace('#', r'\sharp').replace('b', r'\flat') + d + "}"
        out.append((midi, label, int(st) - 1 if st else None))
    return out

def finger(notes):
    notes = [n for n in notes if n != "|"]
    if notes and all(n[2] is not None for n in notes):     # explicit strings: 1@6 = on string 6
        res = [(n[2], n[0] - OPEN[n[2]]) for n in notes]
        bad = [r for r in res if r[1] < 0 or r[1] > 22]
        if bad: raise ValueError("note not playable on the given string: %r" % (bad,))
        return res
    if any(n[2] is not None for n in notes):
        raise ValueError("give a string (@s) for every note of the line, or for none")
    pitches = [n[0] for n in notes]
    for lo in list(range(2, 13)) + [1, 0]:        # box: frets lo..lo+3 (+1 stretch); avoid open strings
        hi = lo + 4; centre = lo + 1.5; res = []; ok = True
        for m in pitches:
            opts = [(s, m - OPEN[s]) for s in range(6) if lo <= m - OPEN[s] <= hi]
            if not opts: ok = False; break
            res.append(min(opts, key=lambda x: (abs(x[1] - centre), x[0])))
        if ok: return res
    raise ValueError("cannot finger %r" % pitches)

def tikz(line, key):
    notes = parse(line, key); pos = iter(finger(notes)); x = 0.6; items = []
    for n in notes:
        if n == "|": items.append(("bar", x)); x += 0.5; continue
        s, f = next(pos); items.append(("note", x, s, f, n[1])); x += 0.8
    w = x + 0.1
    t = [r"\begin{tikzpicture}[x=1cm,y=0.28cm]"]
    for i in range(6):
        t.append(rf"\draw[black!40] (0,{-i}) -- ({w:.2f},{-i});")
        t.append(rf"\node[left,font=\tiny] at (0,{-i}) {{{NAMES[i]}}};")
    t.append(r"\draw[black!60] (0,0) -- (0,-5);" + rf"\draw[black!60] ({w:.2f},0) -- ({w:.2f},-5);")
    for it in items:
        if it[0] == "bar": t.append(rf"\draw[black!60] ({it[1]:.2f},0) -- ({it[1]:.2f},-5);")
        else:
            _, xx, s, f, lab = it
            t.append(rf"\node[fill=white,inner sep=1pt,font=\footnotesize\bfseries] at ({xx:.2f},{-s}) {{{f}}};")
            t.append(rf"\node[font=\scriptsize] at ({xx:.2f},-6.4) {{{lab}}};")
    t.append(r"\end{tikzpicture}")
    return "% Generated by tools/tabs.py -- do not edit\n" + \
           rf"{{\footnotesize\textit{{Guitar, key of {key}:}}}}\\[2pt]" + "\n" + "\n".join(t) + "\n"

# Harmonic groups of the pattern book, in order: (id used in "% group: <id>", title)
GROUPS = [
    ("scales-arpeggios", r"Scales and arpeggios"),
    ("ii-v-i-major", r"Major ii--V--I"),
    ("ii-v-i-minor", r"Minor ii--V--i"),
    ("secondary-dominants", r"Secondary dominants"),
    ("chromatic", r"Chromatic motion and substitutions"),
    ("one-chord", r"Over one chord"),
    ("riffs", r"Riffs and phrases"),
]

def sortkey(title):
    """Plain-text sort key of a TeX title."""
    t = re.sub(r"\\[a-zA-Z]+", "", title)
    return re.sub(r"[^a-z0-9 ]", "", t.lower()).strip()

def main():
    os.makedirs(OUT, exist_ok=True)
    ids = []
    for p in sorted(glob.glob(os.path.join(PAT, "*.tex"))):
        pid = os.path.basename(p)[:-4]; ids.append(pid)
        for i, m in enumerate(re.finditer(r"\\patterntab(?:\[(\w+)\])?\{([^}]*)\}", open(p).read()), 1):
            key = m.group(1) or "G"
            open(os.path.join(OUT, f"{pid}-{i}.tex"), "w").write(tikz(m.group(2), key))
    # Pattern book: one chapter per harmonic group (GROUPS order), patterns alphabetical
    # by title inside each group; plus an alphabetical index of all patterns.
    info = {}
    for pid in ids:
        src = open(os.path.join(PAT, pid + ".tex")).read()
        g = re.search(r"^% group: (\S+)", src, re.M)
        if not g or g.group(1) not in dict(GROUPS):
            raise SystemExit(f"patterns/{pid}.tex: missing or unknown '% group:' line "
                             f"(one of: {', '.join(k for k, _ in GROUPS)})")
        title = re.search(r"\\begin\{patternbox\}\{((?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*)\}", src).group(1)
        info[pid] = (g.group(1), title, sortkey(title))
    with open(os.path.join(OUT, "list.tex"), "w") as f:
        f.write("% Generated by tools/tabs.py -- patterns by harmonic group, alphabetical\n")
        for gid, gtitle in GROUPS:
            members = sorted((p for p in ids if info[p][0] == gid), key=lambda p: info[p][2])
            if not members: continue
            f.write(f"\\patterngroup{{{gtitle}}}\n")
            for pid in members: f.write(f"\\pattern{{{pid}}}\n")
    with open(os.path.join(OUT, "index.tex"), "w") as f:
        f.write("% Generated by tools/tabs.py -- alphabetical index of patterns\n")
        f.write("\\chapter*{Index of patterns}\n\\addcontentsline{toc}{chapter}{Index of patterns}\n"
                "\\markboth{Index of patterns}{Index of patterns}\n\\begingroup\\parindent=0pt\n")
        for pid in sorted(ids, key=lambda p: info[p][2]):
            g, title, _ = info[pid]
            f.write(f"{title} {{\\footnotesize\\textit{{({dict(GROUPS)[g]})}}}}"
                    f"\\dotfill\\ \\pageref{{pat:{pid}}}\\par\\smallskip\n")
        f.write("\\endgroup\n")
    print(len(ids), "patterns")

if __name__ == "__main__":
    main()
